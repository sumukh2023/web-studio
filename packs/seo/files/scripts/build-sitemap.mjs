#!/usr/bin/env node
/**
 * dist/sitemap.xml and dist/robots.txt, from src/seo/seo.config.json.
 *
 * `lastmod` is the last COMMIT to touch a route's `sources`, not a date a
 * human remembers to bump. No git (or a shallow clone) simply omits it.
 * Routes with `"sitemap": false` are prerendered but not nominated.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = join(ROOT, 'dist');
const config = JSON.parse(await readFile(join(ROOT, 'src/seo/seo.config.json'), 'utf8'));
const ORIGIN = config.origin.replace(/\/+$/, '');

if (!existsSync(DIST)) {
  console.error('[sitemap] dist/ not found; run `vite build` first.');
  process.exit(1);
}

function lastCommitDate(sources = []) {
  const present = sources.filter((s) => existsSync(join(ROOT, s)));
  if (!present.length) return null;
  try {
    const out = execFileSync('git', ['log', '-1', '--format=%cs', '--', ...present], {
      cwd: ROOT,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    return /^\d{4}-\d{2}-\d{2}$/.test(out) ? out : null;
  } catch {
    return null;
  }
}

const listed = config.routes.filter((r) => r.sitemap !== false);
const body = listed
  .map(({ path, sources }) => {
    const lastmod = lastCommitDate(sources);
    return [
      '  <url>',
      `    <loc>${ORIGIN}${path === '/' ? '/' : path}</loc>`,
      ...(lastmod ? [`    <lastmod>${lastmod}</lastmod>`] : []),
      '  </url>',
    ].join('\n');
  })
  .join('\n');

await writeFile(
  join(DIST, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by scripts/build-sitemap.mjs from src/seo/seo.config.json. -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${body}\n</urlset>\n`,
  'utf8'
);

/* robots.txt. NO TRAILING SLASH on a Disallow: `/admin/` misses `/admin`
   itself. A Disallow is not a noindex, which is why private paths also get a
   noindex meta from <Seo /> (and, with security-headers, X-Robots-Tag). */
const robots = [
  'User-agent: *',
  'Allow: /',
  ...config.privatePrefixes.map((p) => `Disallow: ${p.replace(/\/+$/, '')}`),
  '',
  `Sitemap: ${ORIGIN}/sitemap.xml`,
  '',
].join('\n');
// A hand-written public/robots.txt wins; Vite copied it into dist/ already.
if (!existsSync(join(ROOT, 'public', 'robots.txt'))) await writeFile(join(DIST, 'robots.txt'), robots, 'utf8');

console.log(`[sitemap] ${listed.length} URLs in dist/sitemap.xml; robots.txt written.`);
